#!/usr/bin/env python3
"""Copies each grammar's highlights.scm out of the SwiftPM checkouts into one generated Swift
file, so the queries ship inside the binary and stay in step with the pinned grammar commits.

Run after `swift package resolve` (or whenever a grammar is bumped in Package.swift):
    Scripts/vendor-queries.py [checkouts-dir]
"""
import pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CHECKOUTS = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / ".build" / "checkouts"
OUT = ROOT / "Sources" / "SyntaxHighlight" / "HighlightQueries.swift"

# Swift identifier → query file (relative to the checkouts dir). A `; inherits: x` comment at the
# top of a query pulls in another language's file first, so the inheriting file's patterns win.
QUERIES = {
    "go": "tree-sitter-go/queries/highlights.scm",
    "python": "tree-sitter-python/queries/highlights.scm",
    "bash": "tree-sitter-bash/queries/highlights.scm",
    "fish": "../../Sources/TreeSitterFish/queries/highlights.scm",
    "markdown": "tree-sitter-markdown/tree-sitter-markdown/queries/highlights.scm",
    "markdownInline": "tree-sitter-markdown/tree-sitter-markdown-inline/queries/highlights.scm",
    "swift": "tree-sitter-swift/queries/highlights.scm",
    "cpp": "tree-sitter-cpp/queries/highlights.scm",
    "c": "tree-sitter-c/queries/highlights.scm",
    "rust": "tree-sitter-rust/queries/highlights.scm",
    "json": "tree-sitter-json/queries/highlights.scm",
    "yaml": "tree-sitter-yaml/queries/highlights.scm",
    "toml": "tree-sitter-toml/queries/highlights.scm",
    "javascript": "tree-sitter-javascript/queries/highlights.scm",
    "typescript": "tree-sitter-typescript/queries/highlights.scm",
    "html": "tree-sitter-html/queries/highlights.scm",
    "css": "tree-sitter-css/queries/highlights.scm",
    "ruby": "tree-sitter-ruby/queries/highlights.scm",
    "java": "tree-sitter-java/queries/highlights.scm",
    "kotlin": "tree-sitter-kotlin/queries/highlights.scm",
    "lua": "tree-sitter-lua/queries/highlights.scm",
    "dockerfile": "tree-sitter-dockerfile/queries/highlights.scm",
    "objc": "tree-sitter-objc/queries/highlights.scm",
    "haskell": "tree-sitter-haskell/queries/highlights.scm",
    "elixir": "tree-sitter-elixir/queries/highlights.scm",
    "sql": "tree-sitter-sql/queries/highlights.scm",
    "php": "tree-sitter-php/queries/highlights.scm",
    "scala": "tree-sitter-scala/queries/highlights.scm",
    "xml": "tree-sitter-xml/queries/xml/highlights.scm",
}

INHERITS = re.compile(r"^;+\s*inherits:\s*([\w,\s]+)$", re.MULTILINE)

def load(name: str) -> str:
    path = (CHECKOUTS / QUERIES[name]).resolve()
    text = path.read_text()
    parents = []
    for match in INHERITS.finditer(text):
        parents += [p.strip() for p in match.group(1).split(",") if p.strip()]
    text = INHERITS.sub("", text)
    return "".join(load(p) + "\n" for p in parents) + f"; ---- {QUERIES[name]} ----\n" + text

def revision(name: str) -> str:
    repo = CHECKOUTS / QUERIES[name].split("/")[0] if name in QUERIES else CHECKOUTS / f"tree-sitter-{name}"
    if not (repo / ".git").exists():
        return "vendored"
    return subprocess.run(["git", "-C", str(repo), "rev-parse", "--short", "HEAD"],
                          capture_output=True, text=True, check=True).stdout.strip()

# Grammars whose manifest looks for src/scanner.c with a path relative to the manifest process's
# working directory, which is not the package: the scanner never compiles and its symbols are
# missing at link time. Their scanners (and the headers they include) are copied into one local
# C target, pinned to the same commit as the grammar itself.
SCANNERS = ["css", "javascript", "lua", "python", "yaml"]
SCANNER_DIR = ROOT / "Sources" / "TreeSitterScanners"

for name in SCANNERS:
    src = CHECKOUTS / f"tree-sitter-{name}" / "src"
    dest = SCANNER_DIR / name
    (dest / "tree_sitter").mkdir(parents=True, exist_ok=True)
    for file in src.glob("*.c"):
        if file.name != "parser.c":
            (dest / file.name).write_bytes(file.read_bytes())
    for header in (src / "tree_sitter").glob("*.h"):
        (dest / "tree_sitter" / header.name).write_bytes(header.read_bytes())
    (dest / "REVISION").write_text(revision(name) + "\n")
print(f"vendored scanners: {', '.join(SCANNERS)}")

parts = ["// Generated by Scripts/vendor-queries.py — do not edit. Each query is the grammar's own",
         "// highlights.scm at the commit pinned in Package.swift.",
         "",
         "enum HighlightQueries {"]
for name in QUERIES:
    body = load(name)
    assert '"""#' not in body, name
    parts.append(f"    /// {QUERIES[name]} @ {revision(name)}")
    parts.append(f'    static let {name} = #"""\n{body}\n"""#')
    parts.append("")
parts.append("}")
OUT.write_text("\n".join(parts) + "\n")
print(f"wrote {OUT.relative_to(ROOT)} ({len(QUERIES)} queries)")
